function N = level_session_report(day, varargin)
%LEVEL_SESSION_REPORT  One rig session's water-level runs, measured and against the model fitted to them.
%
%   N = level_session_report('2026-10-26')
%   ... 'Note', 'text'   an observation the data cannot state, printed under the title
%   ... 'Drain', 'text'  how water left the jar during the session (printed with the flows)
%   ... 'Out', folder    write there instead of results/reports/water_level/<day>
%
%   Reads the session's WATER runs from data/ and, for every run:
%     - what was sent (band, geometry), how long it ran, how it ended, the pump starts
%     - the HC-SR04 as the firmware reported it: frames whose level changed, steps over 1.5 cm
%       between consecutive frames with the pump off (water cannot move that fast)
%   For every run with at least one complete pump cycle (levellab.level.cycleAnalysis):
%     - rise rate with the pump ON, fall rate with it OFF, Q_in and Q_out (x jar area)
%     - T_on, T_off, the period, the overshoot past Lmax, the equivalent delay
%       (overshoot / rise rate: how long the water kept coming after the switch-off)
%     - the run simulated with its own band and starting level on a model whose pump flow and
%       outflow are the ones measured in that run (grey under the rig's trace)
%   The same runs go through Simulink (water_level_plant.slx, dashed) when it is installed.
%   Writes results/reports/water_level/<day>/REPORT.md and *.png. Every number comes from data/.
    o = struct('Note', '', 'Drain', '', 'Out', '');
    for k = 1:2:numel(varargin), o.(varargin{k}) = varargin{k + 1}; end
    root = levellab.repoRoot();
    out = fullfile(root, 'results', 'reports', 'water_level', day);
    if ~isempty(o.Out), out = o.Out; end
    if ~isfolder(out), mkdir(out); end
    Rg = levellab.data.register(); Rg = Rg(strcmp(Rg.apparatus, 'WATER'), :);
    Rg = Rg(startsWith(Rg.created, day), :);
    hasSimulink = ~isempty(ver('simulink')) && license('test', 'Simulink');
    L = {}; N = struct('day', day, 'runs', height(Rg), 'cycles', struct([]));
    say('# Water-level control: rig session %s', day);
    say('');
    say(['Generated by `matlab/scripts/level_session_report.m` from `data/` (%d runs). A 15 L jar filled from a ' ...
         '500 L tank by a 0.5 HP-class single-phase pump switched by a Fotek SSR-40DA, an HC-SR04 above the jar, ' ...
         'an Arduino Uno running `firmware/level_controller` (on-off, guards on). Levels are percent of the depth ' ...
         'entered as 100 %%; the jar''s inside dimensions are ESTIMATED (24 x 24 cm), so flows in L/min carry that ' ...
         'uncertainty, while times and rates in cm/s do not.'], height(Rg));
    say('');
    if ~isempty(o.Note), say('**Observation.** %s', o.Note); say(''); end

    % ------------------------------------------------------------------ the runs
    say('## The runs');
    say('| run | mission | band sent (%%) | sensor height / 100 %% (cm) | firmware | length (s) | pump starts | ended |');
    say('|---|---|---:|---:|---|---:|---:|---|');
    runs = cell(height(Rg), 1);
    for k = 1:height(Rg)
        [T, v, J] = loadRun(Rg.run_id{k}); runs{k} = {T, v, J};
        starts = nnz(diff(double(T.pump > 0)) > 0) + double(T.pump(1) > 0);
        say('| `%s` | %s | %g-%g | %.1f / %.1f | %s | %.0f | %d | %s |', Rg.run_id{k}, Rg.mission{k}, v.Lmin, v.Lmax, ...
            100 * v.h_sensor, 100 * v.tank_H, strrep(J.firmware, 'water_level_lab ', ''), T.t_s(end), starts, Rg.result{k});
    end
    say('');

    % ------------------------------------------------------------------ the sensor
    say('## The sensor, as the firmware reported it');
    say(['The firmware pings once every 100 ms and reports the median of the last five accepted pings; a ping more than ' ...
         '3 cm (plus 2 cm/s of elapsed time) from that median is rejected as an echo the water could not have produced. ' ...
         'A level that holds for many frames therefore means either a still surface or rejected pings.']);
    say('');
    say('| run | frames | frames whose level changed | steps > 1.5 cm, pump off | lost echoes (level NaN) | ripple about the trend, longest pump-off stretch (cm, 1 sigma) | its dominant period (s) |');
    say('|---|---:|---:|---:|---:|---:|---:|');
    for k = 1:height(Rg)
        T = runs{k}{1}; y = T.level_cm; off = T.pump == 0;
        d = abs(diff(y)); jumps = nnz(d > 1.5 & off(2:end));
        [rs, rp] = ripple(T);
        say('| `%s` | %d | %d (%.0f %%) | %d | %d | %s | %s |', Rg.run_id{k}, height(T), nnz(d > 0), 100 * nnz(d > 0) / max(1, numel(d)), ...
            jumps, nnz(~isfinite(T.level_pct)), n0(rs, '%.2f'), n0(rp, '%.1f'));
    end
    say('');

    % ------------------------------------------------------------------ on-off cycles
    say('## On-off cycles');
    if ~isempty(o.Drain), say('%s', o.Drain); say(''); end
    say('| run | band (%%) | cycles | rise, pump ON (cm/s) | fall, pump OFF (cm/s) | Q_in (L/min) | Q_out (L/min) | T_on (s) | T_off (s) | period (s) | overshoot past Lmax (cm) | equivalent delay (s) |');
    say('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|');
    figs = {};
    for k = 1:height(Rg)
        [T, v] = deal(runs{k}{1}, runs{k}{2});
        ok = isfinite(T.level_cm) & T.flags ~= 0;            % frames of a live run (flags 0: stopped)
        ok = ok & bitand(double(T.flags), 1) == 1;
        A = v.tank_L * v.tank_W; LmaxCm = v.Lmax / 100 * v.tank_H * 100;
        if nnz(diff(double(T.pump(ok) > 0)) ~= 0) < 2, continue; end
        r = levellab.level.cycleAnalysis(T.t_s(ok), T.level_cm(ok), T.pump(ok), A, LmaxCm);
        if r.nCycles < 1, continue; end
        if ~(r.fall_cm_s > 0)                                % no outflow: the switchings were not cycles of the water
            say('| `%s` | %g-%g | (%d) | %.2f | %.3f | - | - | - | - | - | - | - |', Rg.run_id{k}, v.Lmin, v.Lmax, r.nCycles, r.rise_cm_s, r.fall_cm_s);
            continue
        end
        delayEq = r.overshoot_cm / r.rise_cm_s;
        say('| `%s` | %g-%g | %d | %.2f | %.3f | %.1f | %.2f | %.1f | %.0f | %.0f | %.1f | %.1f |', Rg.run_id{k}, v.Lmin, v.Lmax, ...
            r.nCycles, r.rise_cm_s, r.fall_cm_s, r.Qin_mL_s * 0.06, r.Qout_mL_s * 0.06, r.Ton_s, r.Toff_s, r.period_s, ...
            r.overshoot_cm, delayEq);
        S = simulateRun(T(ok, :), v, r);
        figs{end + 1} = {T, S, v, sprintf('on-off %g-%g %% (%s)', v.Lmin, v.Lmax, Rg.run_id{k})}; %#ok<AGROW>
        p = predicted(v, r, S);
        r.run_id = Rg.run_id{k}; r.pred = p; r.delayEq = delayEq;
        if isempty(N.cycles), N.cycles = r; else, N.cycles(end + 1) = r; end
    end
    say('');
    say(['A run whose level did not fall with the pump off (no outflow) has no real cycles: its switchings are shown in brackets and not analysed. Q_out = jar area x fall rate; Q_in = jar area x rise rate + Q_out. The overshoot is the highest level after ' ...
         'each switch-off minus Lmax, averaged over the complete cycles; dividing it by the rise rate gives the time ' ...
         'the level kept rising after the pump was switched off (the pipe emptying, the run-down, the waves).']);
    say('');
    if ~isempty(N.cycles)
        say('### Against the formulas and the model');
        say('| run | T_on = A dL / (Q_in - Q_out) (s) | T_on, rig (s) | T_on, MATLAB / Simulink (s) | T_off = A dL / Q_out (s) | T_off, rig (s) | T_off, MATLAB / Simulink (s) | overshoot, rig / MATLAB (cm) | MATLAB vs Simulink, RMS (cm) |');
        say('|---|---:|---:|---:|---:|---:|---:|---:|---:|');
        for c = N.cycles
            say('| `%s` | %.1f | %.1f | %s / %s | %.0f | %.0f | %s / %s | %.1f / %s | %s |', c.run_id, c.pred.Ton, c.Ton_s, ...
                n0(c.pred.TonSim, '%.1f'), n0(c.pred.TonSL, '%.1f'), c.pred.Toff, c.Toff_s, ...
                n0(c.pred.ToffSim, '%.0f'), n0(c.pred.ToffSL, '%.0f'), c.overshoot_cm, n0(c.pred.overSim, '%.1f'), n0(c.pred.agree, '%.2f'));
        end
        say('');
        say(['- : the run ended before the model completed that phase. The model runs each run''s own band from its own starting level, with the pump flow and the outflow ' ...
             'measured in that run, the firmware''s guards and minimum times, and the ESTIMATED 1.5 s from switch-on to ' ...
             'water arriving. Where the rig''s overshoot exceeds the model''s, the water kept arriving longer than 1.5 s ' ...
             'after the switch-off, or the waves from the jet lifted the reading.']);
        say('');
        multiPlot(figs, 'onoff_cycles.png');
        say('![On-off cycles](onoff_cycles.png)'); say('');
    end

    % ------------------------------------------------------------------ every run
    say('## Every run');
    allFigs = cellfun(@(c, id) {c{1}, [], c{2}, id}, runs, Rg.run_id, 'UniformOutput', false);
    multiPlot(allFigs, 'all_runs.png');
    say('![All runs](all_runs.png)'); say('');

    say('## Runs stopped before their end');
    st = Rg(~startsWith(Rg.result, 'FINISHED'), :);
    if height(st) == 0, say('None.'); end
    for k = 1:height(st), say('- `%s`: %s', st.run_id{k}, st.result{k}); end
    fid = fopen(fullfile(out, 'REPORT.md'), 'w'); fprintf(fid, '%s\n', L{:}); fclose(fid);
    fprintf('report -> %s\n', fullfile(out, 'REPORT.md'));

    % ================================================================== helpers
    function [T, v, J] = loadRun(id)
        T = readtable(fullfile(root, 'data', 'raw', 'water_level', [id '.csv']));
        J = jsondecode(fileread(fullfile(root, 'data', 'metadata', 'water_level', [id '.json'])));
        v = J.config_sent.values;
    end
    function S = simulateRun(T, v, r)
        c = levellab.level.defaultConfig();
        spec = struct('tank_L', v.tank_L, 'tank_W', v.tank_W, 'tank_H', v.tank_H, 'h_sensor', v.h_sensor, ...
            'Q_max', r.Qin_mL_s * 0.06, 'H_max', Inf, 'delay', v.delay, 'T_air', v.T_air);
        c.P = levellab.level.physics(spec);
        c.P.res_us = 0.001; c.P.noise_us = 0.001;
        c.mode = 'ONOFF'; c.Lmin = v.Lmin; c.Lmax = v.Lmax;
        c.outflow = 'constant'; c.Qout = r.Qout_mL_s * 0.06;
        c.h0 = T.level_pct(find(isfinite(T.level_pct), 1)); c.Tend = T.t_s(end) - T.t_s(1);
        c.pump_kind = v.pump_kind;
        S = levellab.level.simulate(c); S.t = S.t + T.t_s(1);
        S.sl = [];                                           % the same run in Simulink, when installed
        if hasSimulink
            R = run_level_simulink(c);
            S.sl = struct('t', R.t + T.t_s(1), 'level', R.level, 'on', R.q > 0.5 * c.P.Q_max);
        end
    end
    function p = predicted(v, r, S)
        A = v.tank_L * v.tank_W * 1e4; dL = (v.Lmax - v.Lmin) / 100 * v.tank_H * 100;   % cm^2, cm
        p.Ton = A * dL / (r.Qin_mL_s - r.Qout_mL_s); p.Toff = A * dL / r.Qout_mL_s;
        s = levellab.level.cycleAnalysis(S.t, S.level / 100 * v.tank_H * 100, S.u, v.tank_L * v.tank_W, v.Lmax / 100 * v.tank_H * 100);
        p.TonSim = s.Ton_s; p.ToffSim = s.Toff_s;
        offs = find(diff(S.u > 0) < 0) + 1; ov = nan(size(offs));          % highest level within 20 s of each switch-off
        for i = 1:numel(offs), w = S.t >= S.t(offs(i)) & S.t < S.t(offs(i)) + 20; ov(i) = max(S.level(w)) / 100 * v.tank_H * 100 - v.Lmax / 100 * v.tank_H * 100; end
        p.overSim = mean(ov);
        p.TonSL = NaN; p.ToffSL = NaN; p.agree = NaN;
        if ~isempty(S.sl)
            q = levellab.level.cycleAnalysis(S.sl.t, S.sl.level / 100 * v.tank_H * 100, S.sl.on, v.tank_L * v.tank_W, v.Lmax / 100 * v.tank_H * 100);
            p.TonSL = q.Ton_s; p.ToffSL = q.Toff_s;
            p.agree = sqrt(mean((interp1(S.sl.t, S.sl.level, S.t, 'linear', 'extrap') - S.level).^2)) / 100 * v.tank_H * 100;
        end
    end
    function multiPlot(F, file)
        n = numel(F); fig = figure('Visible', 'off', 'Color', 'w', 'Position', [0 0 1100 300 * n]);
        if isprop(fig, 'Theme'), fig.Theme = 'light'; end      % R2025a+: figures follow the desktop theme otherwise
        tl = tiledlayout(fig, n, 1, 'TileSpacing', 'compact', 'Padding', 'compact');
        for i = 1:n
            [T, S, v, ttl] = F{i}{:};
            ax = nexttile(tl); hold(ax, 'on'); grid(ax, 'on'); box(ax, 'on');
            on = T.pump > 0; tOn = T.t_s; yOn = 105 * ones(size(tOn)); yOn(~on) = NaN;
            if ~isempty(S)
                plot(ax, S.t, S.level, 'Color', [0.65 0.65 0.65], 'LineWidth', 2.2, 'DisplayName', 'model (MATLAB)');
                if ~isempty(S.sl), plot(ax, S.sl.t, S.sl.level, 'k--', 'LineWidth', 0.9, 'DisplayName', 'model (Simulink)'); end
            end
            plot(ax, T.t_s, T.level_pct, 'Color', [0 0.45 0.74], 'LineWidth', 1.1, 'DisplayName', 'rig (HC-SR04)');
            plot(ax, tOn, yOn, 'Color', [0.85 0.33 0.1], 'LineWidth', 5, 'DisplayName', 'pump ON');
            yline(ax, v.Lmin, '--', 'Lmin', 'Color', [0.3 0.3 0.3], 'HandleVisibility', 'off');
            yline(ax, v.Lmax, '--', 'Lmax', 'Color', [0.3 0.3 0.3], 'HandleVisibility', 'off');
            yline(ax, 92, ':', 'overflow guard', 'Color', [0.8 0 0], 'HandleVisibility', 'off');
            ylim(ax, [0 110]); xlim(ax, [0 max(T.t_s(end), 1)]);
            ylabel(ax, 'level (%)'); title(ax, ttl, 'Interpreter', 'none', 'FontWeight', 'normal');
            if i == 1, legend(ax, 'Location', 'southeast'); end
        end
        xlabel(ax, 'time (s)');
        exportgraphics(fig, fullfile(out, file), 'Resolution', 110); close(fig);
    end
    function [sd, per] = ripple(T)
        % the longest stretch (>= 30 s) of a live run with the pump off: what is left about a straight line
        live = bitand(double(T.flags), 1) == 1 & T.pump == 0 & isfinite(T.level_cm);
        e = diff([0; live; 0]); a = find(e == 1); b = find(e == -1) - 1;
        sd = NaN; per = NaN; if isempty(a), return; end
        [~, j] = max(b - a); i = a(j):b(j); t = T.t_s(i);
        if t(end) - t(1) < 30, return; end
        y = T.level_cm(i); r = y - polyval(polyfit(t, y, 1), t);
        n = numel(r); Y = abs(fft(r)); f = (0:n - 1)' / (n * median(diff(t)));
        band = f > 1 / 20 & f < 0.5 / median(diff(t));          % periods from 20 s down to the Nyquist limit
        [~, m] = max(Y .* band); sd = std(r); per = 1 / f(m);
    end
    function s = n0(x, f, none)
        if nargin < 3, none = '-'; end
        if isfinite(x), s = sprintf(f, x); else, s = none; end
    end
    function say(fmt, varargin)
        L{end + 1} = sprintf(fmt, varargin{:});
    end
end
